  S.ensureIconPack = function (pack) {
    if (pack !== 'ph' || typeof document === 'undefined') return;
    if (document.getElementById('ph-icon-css')) return;
    var link = document.createElement('link');
    link.id = 'ph-icon-css';
    link.rel = 'stylesheet';
    link.href = 'https://unpkg.com/@phosphor-icons/web@2.1.1/src/regular/style.css';
    document.head.appendChild(link);
  };

  S.icon = function (name, extraClass) {
    name = String(name || '').trim();
    if (!name) return '';
    var cls = extraClass ? ' ' + extraClass : '';
    var prefix = '';
    var m = name.match(/^(lucide|ph|msr|mso|mss|ms):/);
    if (m) {
      prefix = m[1];
      name = name.slice(m[0].length);
      if (prefix === 'ms') prefix = 'msr';
    }

    if (prefix === 'ph' || (!prefix && S.phosphorIcons.indexOf(name) > -1)) {
      if (!prefix && S.lucide[name]) {
        /* prefer the bundled SVG when a bare name is ambiguous */
        prefix = 'lucide';
      } else {
        S.ensureIconPack('ph');
        return '<i class="ph ph-' + S.util.esc(name) + ' ph-ico' + cls + '" aria-hidden="true"></i>';
      }
    }

    var inner = S.lucide[name];
    if (prefix !== 'msr' && prefix !== 'mso' && prefix !== 'mss' && inner) {
      return '<svg class="icn' + cls + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" ' +
        'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' + inner + '</svg>';
    }

    var familyClass = prefix === 'mso' ? ' mi mso' : prefix === 'mss' ? ' mi mss' : ' mi';
    return '<span class="' + familyClass.trim() + cls + '" aria-hidden="true">' + S.util.esc(name) + '</span>';
  };
