/* Generates Color.kt, Type.kt, Shape.kt, Dimens.kt, and Theme.kt
   for Android Jetpack Compose Material 3 based on Droid Lab tokens. */
(function () {
  var S = window.Studio = window.Studio || {};
  S.exporters = S.exporters || {};
  var android = S.exporters.android = S.exporters.android || {};
  var U = S.util || {};

  function hex(value, fallback) {
    var text = String(value || fallback || '#6750A4').replace('#', '').trim();
    if (text.length === 3) text = text.split('').map(function (c) { return c + c; }).join('');
    if (!/^[0-9a-fA-F]{6,8}$/.test(text)) text = String(fallback || '#6750A4').replace('#', '');
    return text.toUpperCase();
  }

  function color(value, fallback) {
    var text = hex(value, fallback);
    if (text.length === 6) return 'Color(0xFF' + text + ')';
    return 'Color(0x' + text + ')';
  }

  function weightName(weight) {
    return ({
      100: 'Thin', 200: 'ExtraLight', 300: 'Light', 400: 'Normal',
      500: 'Medium', 600: 'SemiBold', 700: 'Bold', 800: 'ExtraBold', 900: 'Black'
    })[Number(weight)] || 'Normal';
  }

  function fontSlug(name) {
    return String(name || 'inter').toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '') || 'font';
  }

  var ThemeGenerator = android.ThemeGenerator = {
    generateColorKt: function (packageName, theme) {
      theme = theme || {};
      var p = theme.primary || '#6750A4';
      var dark = !!theme.dark;

      // Generate palette colors
      var lightPrimary = p;
      var lightOnPrimary = (U.onColor ? U.onColor(p) : '#FFFFFF');
      var lightPrimaryContainer = (U.mix ? U.mix(p, '#ffffff', 0.8) : '#EADDFF');
      var lightOnPrimaryContainer = (U.mix ? U.mix(p, '#000000', 0.72) : '#21005D');
      var lightSecondaryContainer = (U.mix ? U.mix(p, '#ffffff', 0.72) : '#E8DEF8');
      var lightOnSecondaryContainer = (U.mix ? U.mix(p, '#000000', 0.68) : '#1D192B');
      var lightBackground = '#FFFBFE';
      var lightSurface = '#FFFBFE';
      var lightSurfaceVariant = '#E7E0EC';
      var lightOnSurface = '#1C1B1F';
      var lightOnSurfaceVariant = '#49454F';
      var lightOutline = '#79747E';

      var darkPrimary = (U.mix ? U.mix(p, '#ffffff', 0.55) : '#D0BCFF');
      var darkOnPrimary = (U.mix ? U.mix(p, '#000000', 0.65) : '#381E72');
      var darkPrimaryContainer = (U.mix ? U.mix(p, '#000000', 0.5) : '#4F378B');
      var darkOnPrimaryContainer = (U.mix ? U.mix(p, '#ffffff', 0.86) : '#EADDFF');
      var darkSecondaryContainer = (U.mix ? U.mix(p, '#000000', 0.62) : '#4A4458');
      var darkOnSecondaryContainer = (U.mix ? U.mix(p, '#ffffff', 0.86) : '#E8DEF8');
      var darkBackground = '#141218';
      var darkSurface = '#141218';
      var darkSurfaceVariant = '#49454F';
      var darkOnSurface = '#E6E0E9';
      var darkOnSurfaceVariant = '#CAC4D0';
      var darkOutline = '#938F99';

      return [
        'package ' + packageName + '.ui.theme',
        '',
        'import androidx.compose.ui.graphics.Color',
        '',
        '/**',
        ' * Design tokens generated by Droid Lab for Material 3.',
        ' */',
        '// Light Scheme',
        'val LightPrimary = ' + color(lightPrimary),
        'val LightOnPrimary = ' + color(lightOnPrimary),
        'val LightPrimaryContainer = ' + color(lightPrimaryContainer),
        'val LightOnPrimaryContainer = ' + color(lightOnPrimaryContainer),
        'val LightSecondaryContainer = ' + color(lightSecondaryContainer),
        'val LightOnSecondaryContainer = ' + color(lightOnSecondaryContainer),
        'val LightBackground = ' + color(lightBackground),
        'val LightSurface = ' + color(lightSurface),
        'val LightSurfaceVariant = ' + color(lightSurfaceVariant),
        'val LightOnSurface = ' + color(lightOnSurface),
        'val LightOnSurfaceVariant = ' + color(lightOnSurfaceVariant),
        'val LightOutline = ' + color(lightOutline),
        '',
        '// Dark Scheme',
        'val DarkPrimary = ' + color(darkPrimary),
        'val DarkOnPrimary = ' + color(darkOnPrimary),
        'val DarkPrimaryContainer = ' + color(darkPrimaryContainer),
        'val DarkOnPrimaryContainer = ' + color(darkOnPrimaryContainer),
        'val DarkSecondaryContainer = ' + color(darkSecondaryContainer),
        'val DarkOnSecondaryContainer = ' + color(darkOnSecondaryContainer),
        'val DarkBackground = ' + color(darkBackground),
        'val DarkSurface = ' + color(darkSurface),
        'val DarkSurfaceVariant = ' + color(darkSurfaceVariant),
        'val DarkOnSurface = ' + color(darkOnSurface),
        'val DarkOnSurfaceVariant = ' + color(darkOnSurfaceVariant),
        'val DarkOutline = ' + color(darkOutline),
        ''
      ].join('\n');
    },

    generateTypeKt: function (packageName, theme, fontsUsed, blockOverrides) {
      theme = theme || {};
      var fonts = theme.fonts || {};
      var uiFont = fonts.ui || 'Inter';
      var displayFont = fonts.display || uiFont;
      var type = theme.type || {};
      var baseSize = Number(type.size) || 15;
      var baseWeight = Number(type.weight) || 400;
      var letterSpacing = Number(type.spacing) || 0;

      var lines = [
        'package ' + packageName + '.ui.theme',
        '',
        'import androidx.compose.material3.Typography',
        'import androidx.compose.ui.text.TextStyle',
        'import androidx.compose.ui.text.font.FontFamily',
        'import androidx.compose.ui.text.font.FontWeight',
        'import androidx.compose.ui.unit.sp',
        '',
        '/**',
        ' * Typography specification generated by Droid Lab.',
        ' * Primary UI Font: ' + uiFont + ', Display Font: ' + displayFont + '.',
        ' */',
        '// Font Families (System fallback or bundled res/font)',
        'val UiFont = FontFamily.Default // Set to FontFamily(Font(R.font.' + fontSlug(uiFont) + '_regular)) when bundled',
        'val DisplayFont = FontFamily.Default',
        '',
        'val AppTypography = Typography(',
        '    displayLarge = TextStyle(',
        '        fontFamily = DisplayFont,',
        '        fontWeight = FontWeight.Bold,',
        '        fontSize = 44.sp,',
        '        lineHeight = 52.sp',
        '    ),',
        '    headlineLarge = TextStyle(',
        '        fontFamily = DisplayFont,',
        '        fontWeight = FontWeight.SemiBold,',
        '        fontSize = 30.sp,',
        '        lineHeight = 36.sp',
        '    ),',
        '    headlineMedium = TextStyle(',
        '        fontFamily = DisplayFont,',
        '        fontWeight = FontWeight.SemiBold,',
        '        fontSize = 24.sp,',
        '        lineHeight = 30.sp',
        '    ),',
        '    titleLarge = TextStyle(',
        '        fontFamily = DisplayFont,',
        '        fontWeight = FontWeight.SemiBold,',
        '        fontSize = 20.sp,',
        '        lineHeight = 26.sp',
        '    ),',
        '    titleMedium = TextStyle(',
        '        fontFamily = UiFont,',
        '        fontWeight = FontWeight.Medium,',
        '        fontSize = 16.sp,',
        '        lineHeight = 22.sp',
        '    ),',
        '    bodyLarge = TextStyle(',
        '        fontFamily = UiFont,',
        '        fontWeight = FontWeight.' + weightName(baseWeight) + ',',
        '        fontSize = ' + baseSize + '.sp,',
        '        lineHeight = ' + (baseSize + 6) + '.sp,',
        '        letterSpacing = ' + letterSpacing + '.sp',
        '    ),',
        '    bodyMedium = TextStyle(',
        '        fontFamily = UiFont,',
        '        fontWeight = FontWeight.' + weightName(baseWeight) + ',',
        '        fontSize = ' + Math.max(12, baseSize - 1) + '.sp,',
        '        lineHeight = ' + (baseSize + 4) + '.sp',
        '    ),',
        '    labelLarge = TextStyle(',
        '        fontFamily = UiFont,',
        '        fontWeight = FontWeight.Medium,',
        '        fontSize = 14.sp,',
        '        lineHeight = 20.sp',
        '    ),',
        '    labelMedium = TextStyle(',
        '        fontFamily = UiFont,',
        '        fontWeight = FontWeight.Medium,',
        '        fontSize = 12.sp,',
        '        lineHeight = 16.sp',
        '    )',
        ')',
        ''
      ];

      return lines.join('\n');
    },

    generateShapeKt: function (packageName, theme) {
      var radius = Number(theme && theme.radius) || 18;
      return [
        'package ' + packageName + '.ui.theme',
        '',
        'import androidx.compose.foundation.shape.RoundedCornerShape',
        'import androidx.compose.material3.Shapes',
        'import androidx.compose.ui.unit.dp',
        '',
        '/**',
        ' * Shape definitions based on Droid Lab corner radius: ' + radius + 'dp.',
        ' */',
        'val AppShapes = Shapes(',
        '    extraSmall = RoundedCornerShape(' + Math.max(4, Math.round(radius * 0.4)) + '.dp),',
        '    small = RoundedCornerShape(' + Math.max(6, Math.round(radius * 0.6)) + '.dp),',
        '    medium = RoundedCornerShape(' + radius + '.dp),',
        '    large = RoundedCornerShape(' + (radius + 4) + '.dp),',
        '    extraLarge = RoundedCornerShape(' + (radius + 10) + '.dp)',
        ')',
        ''
      ].join('\n');
    },

    generateDimensKt: function (packageName, device, theme) {
      device = device || {};
      theme = theme || {};
      var w = Number(device.width) || 390;
      var h = Number(device.height) || 844;
      var density = theme.density === 'compact' ? 12 : theme.density === 'comfy' ? 20 : 16;
      var radius = Number(theme.radius) || 18;

      return [
        'package ' + packageName + '.ui.theme',
        '',
        'import androidx.compose.ui.unit.dp',
        '',
        '/**',
        ' * Dimensions and spacing scale converted from Droid Lab.',
        ' */',
        'val DesignScreenWidth = ' + w + '.dp',
        'val DesignScreenHeight = ' + h + '.dp',
        'val AppCornerRadius = ' + radius + '.dp',
        'val ScreenPadding = ' + density + '.dp',
        'val SectionSpacing = ' + Math.round(density * 1.25) + '.dp',
        'val CardGap = ' + Math.round(density * 0.75) + '.dp',
        'val IconDefaultSize = 24.dp',
        'val BottomBarHeight = 80.dp',
        ''
      ].join('\n');
    },

    generateThemeKt: function (packageName, theme) {
      var isDark = !!(theme && theme.dark);
      return [
        'package ' + packageName + '.ui.theme',
        '',
        'import androidx.compose.foundation.isSystemInDarkTheme',
        'import androidx.compose.material3.MaterialTheme',
        'import androidx.compose.material3.darkColorScheme',
        'import androidx.compose.material3.lightColorScheme',
        'import androidx.compose.runtime.Composable',
        '',
        'private val LightColorScheme = lightColorScheme(',
        '    primary = LightPrimary,',
        '    onPrimary = LightOnPrimary,',
        '    primaryContainer = LightPrimaryContainer,',
        '    onPrimaryContainer = LightOnPrimaryContainer,',
        '    secondaryContainer = LightSecondaryContainer,',
        '    onSecondaryContainer = LightOnSecondaryContainer,',
        '    background = LightBackground,',
        '    surface = LightSurface,',
        '    surfaceVariant = LightSurfaceVariant,',
        '    onSurface = LightOnSurface,',
        '    onSurfaceVariant = LightOnSurfaceVariant,',
        '    outline = LightOutline',
        ')',
        '',
        'private val DarkColorScheme = darkColorScheme(',
        '    primary = DarkPrimary,',
        '    onPrimary = DarkOnPrimary,',
        '    primaryContainer = DarkPrimaryContainer,',
        '    onPrimaryContainer = DarkOnPrimaryContainer,',
        '    secondaryContainer = DarkSecondaryContainer,',
        '    onSecondaryContainer = DarkOnSecondaryContainer,',
        '    background = DarkBackground,',
        '    surface = DarkSurface,',
        '    surfaceVariant = DarkSurfaceVariant,',
        '    onSurface = DarkOnSurface,',
        '    onSurfaceVariant = DarkOnSurfaceVariant,',
        '    outline = DarkOutline',
        ')',
        '',
        '/**',
        ' * Custom Material 3 theme matching Droid Lab visual identity.',
        ' */',
        '@Composable',
        'fun DroidLabTheme(',
        '    darkTheme: Boolean = ' + (isDark ? 'true' : 'isSystemInDarkTheme()') + ',',
        '    content: @Composable () -> Unit',
        ') {',
        '    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme',
        '',
        '    MaterialTheme(',
        '        colorScheme = colorScheme,',
        '        typography = AppTypography,',
        '        shapes = AppShapes,',
        '        content = content',
        '    )',
        '}',
        ''
      ].join('\n');
    }
  };
})();
